const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('horizon', {
  platform: process.platform,
  newTab: () => ipcRenderer.send('tab:new'),
  closeTab: (id) => ipcRenderer.send('tab:close', id),
  activateTab: (id) => ipcRenderer.send('tab:activate', id),
  go: (text) => ipcRenderer.send('nav:go', text),
  back: () => ipcRenderer.send('nav:back'),
  forward: () => ipcRenderer.send('nav:forward'),
  reload: () => ipcRenderer.send('nav:reload'),
  stop: () => ipcRenderer.send('nav:stop'),
  home: () => ipcRenderer.send('nav:home'),
  openPanel: (mode, anchor) => ipcRenderer.send('panel:open', mode, anchor),

  setLayout: (left) => ipcRenderer.send('ui:layout', left),
  setAppearance: (patch) => ipcRenderer.send('appearance:set', patch),
  resetAppearance: () => ipcRenderer.send('appearance:reset'),
  pickBackground: () => ipcRenderer.send('appearance:image'),
  setRestoreSession: (on) => ipcRenderer.send('session:restore', on),
  toggleBookmark: () => ipcRenderer.send('bookmark:toggle'),
  openBookmark: (id, newTab) => ipcRenderer.send('bookmark:open', id, newTab),
  removeBookmark: (id) => ipcRenderer.send('bookmark:remove', id),
  renameBookmark: (id, title) => ipcRenderer.send('bookmark:rename', id, title),
  saveGroup: (name) => ipcRenderer.send('group:save', name),
  openGroup: (id) => ipcRenderer.send('group:open', id),
  removeGroup: (id) => ipcRenderer.send('group:remove', id),
  suggest: (text, anchor) => ipcRenderer.send('suggest:query', text, anchor),
  suggestMove: (step) => ipcRenderer.send('suggest:move', step),
  suggestClose: () => ipcRenderer.send('suggest:close'),
  clearHistory: () => ipcRenderer.send('history:clear'),
  historyList: () => ipcRenderer.invoke('history:list'),
  removeSearch: (at) => ipcRenderer.send('history:removeSearch', at),
  removeVisit: (url) => ipcRenderer.send('history:removeVisit', url),
  openUrl: (url, newTab) => ipcRenderer.send('history:open', url, newTab),
  replayIntro: () => ipcRenderer.send('intro:replay'),
  checkUpdate: () => ipcRenderer.send('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),

  onState: (callback) => ipcRenderer.on('state', (_event, state) => callback(state)),
  onProfile: (callback) => ipcRenderer.on('profile', (_event, profile) => callback(profile)),
  onSidebar: (callback) => ipcRenderer.on('sidebar:open', (_event, name) => callback(name)),
  onError: (callback) => ipcRenderer.on('ui:error', (_event, message) => callback(message)),
  onDownloads: (callback) => ipcRenderer.on('downloads', (_event, info) => callback(info)),
  onAccount: (callback) => ipcRenderer.on('account', (_event, state) => callback(state)),
  removeBackground: () => ipcRenderer.send('appearance:removeImage'),
  clearSiteData: () => ipcRenderer.send('sitedata:clear'),
  onFocusAddress: (callback) => ipcRenderer.on('focus-address', () => callback()),
});
